#!/usr/bin/env bash
# gen-env.sh — generate site/.env from sites/<SITE_ID>/site.config.json
#
# Usage:
#   ./gen-env.sh rostpoisk
#   ./gen-env.sh finhelp-ru
#
# The script writes site/.env (overwriting it). FTP password is NOT stored
# in site.config.json — it stays in site/.env manually or via secrets manager.
# The script preserves existing BEGET_FTP_PASS and API keys from site/.env.

set -euo pipefail

SITE_ID="${1:-}"
if [[ -z "$SITE_ID" ]]; then
  echo "Usage: $0 <site_id>" >&2
  exit 1
fi

CONFIG="sites/${SITE_ID}/site.config.json"
if [[ ! -f "$CONFIG" ]]; then
  echo "Error: config not found at $CONFIG" >&2
  exit 1
fi

ENV_FILE="site/.env"

# Preserve secrets that must not live in site.config.json
BEGET_FTP_PASS=""
FIRECRAWL_API_KEY=""
EXA_API_KEY=""

if [[ -f "$ENV_FILE" ]]; then
  BEGET_FTP_PASS=$(grep -E '^BEGET_FTP_PASS=' "$ENV_FILE" | cut -d= -f2- || true)
  FIRECRAWL_API_KEY=$(grep -E '^FIRECRAWL_API_KEY=' "$ENV_FILE" | cut -d= -f2- || true)
  EXA_API_KEY=$(grep -E '^EXA_API_KEY=' "$ENV_FILE" | cut -d= -f2- || true)
fi

# Parse config with python (available in .venv)
read -r -d '' PARSE_SCRIPT << 'PYEOF' || true
import json, sys
c = json.load(open(sys.argv[1]))
d = c.get("deploy", {})
b = c.get("brand", {})
ct = c.get("contacts", {})
f = c.get("form", {})
a = c.get("analytics", {})
fields = {
  "SITE_URL":                    d.get("site_url", ""),
  "PUBLIC_SITE_NAME":            b.get("name", ""),
  "PUBLIC_SITE_NAME_FULL":       b.get("name_full", ""),
  "PUBLIC_METRIKA_ID":           a.get("metrika_id", ""),
  "PUBLIC_COMPANY_PHONE":        ct.get("phone", ""),
  "PUBLIC_COMPANY_PHONE_HREF":   ct.get("phone_href", ""),
  "PUBLIC_COMPANY_PHONE_LABEL":  ct.get("phone_label", ""),
  "PUBLIC_COMPANY_EMAIL":        ct.get("email", ""),
  "PUBLIC_COMPANY_ADDRESS":      ct.get("address", ""),
  "PUBLIC_COMPANY_WORKTIME":     ct.get("worktime", ""),
  "PUBLIC_CONTACT_FORM_ACTION":  f.get("action", "/mail.php"),
  "PUBLIC_CONTACT_FORM_TO":      f.get("to", ""),
  "PUBLIC_CONTACT_FORM_SUBJECT": f.get("subject", ""),
  "YANDEX_METRICA_ID":           "",
  "GTAG_ID":                     a.get("gtag_id", ""),
  "BEGET_HOST":                  d.get("beget_host", ""),
  "BEGET_FTP_USER":              d.get("beget_ftp_user", ""),
  "BEGET_FTP_PATH":              d.get("beget_ftp_path", "/"),
}
for k, v in fields.items():
    print(f"{k}={v}")
PYEOF

PARSED=$(python3 - "$CONFIG" <<< "$PARSE_SCRIPT")

cat > "$ENV_FILE" << EOF
# Generated by gen-env.sh from $CONFIG
# DO NOT EDIT manually — edit $CONFIG instead.
# Secrets (FTP password, API keys) are preserved from previous site/.env.

${PARSED}

FIRECRAWL_API_KEY=${FIRECRAWL_API_KEY}
EXA_API_KEY=${EXA_API_KEY}

BEGET_FTP_PASS=${BEGET_FTP_PASS}
EOF

echo "✓ site/.env written for site_id=${SITE_ID}"
echo "  Review site/.env and fill in any blank secrets before deploying."

#!/usr/bin/env bash
# gen-env.sh — generate site/.env from sites/<SITE_ID>/site.config.json
#
# Usage:
#   ./gen-env.sh rostpoisk
#   ./gen-env.sh finhelp-ru
#
# The script writes site/.env (overwriting it). FTP password is NOT stored
# in site.config.json — it stays in site/.env manually or via secrets manager.
# The script preserves existing BEGET_FTP_PASS and API keys from site/.env.

set -euo pipefail

SITE_ID="${1:-}"
if [[ -z "$SITE_ID" ]]; then
  echo "Usage: $0 <site_id>" >&2
  exit 1
fi

CONFIG="sites/${SITE_ID}/site.config.json"
if [[ ! -f "$CONFIG" ]]; then
  echo "Error: config not found at $CONFIG" >&2
  exit 1
fi

ENV_FILE="site/.env"

# Preserve secrets that must not live in site.config.json
BEGET_FTP_PASS=""
FIRECRAWL_API_KEY=""
EXA_API_KEY=""

if [[ -f "$ENV_FILE" ]]; then
  BEGET_FTP_PASS=$(grep -E '^BEGET_FTP_PASS=' "$ENV_FILE" | cut -d= -f2- || true)
  FIRECRAWL_API_KEY=$(grep -E '^FIRECRAWL_API_KEY=' "$ENV_FILE" | cut -d= -f2- || true)
  EXA_API_KEY=$(grep -E '^EXA_API_KEY=' "$ENV_FILE" | cut -d= -f2- || true)
fi

# Parse config with python (available in .venv)
read -r -d '' PARSE_SCRIPT << 'PYEOF' || true
import json, sys, hashlib
from pathlib import Path

c = json.load(open(sys.argv[1]))
site_id = sys.argv[2] if len(sys.argv) > 2 else ""
d = c.get("deploy", {})
b = c.get("brand", {})
ct = c.get("contacts", {})
f = c.get("form", {})
a = c.get("analytics", {})

# Load niche section_labels with deterministic variant selection (F9.4)
niche_labels: dict[str, str] = {}
niche_id = c.get("niche", "")
if niche_id:
    try:
        niches_dir = Path(sys.argv[1]).resolve().parent.parent.parent / "niches"
        niche_data = json.loads((niches_dir / f"{niche_id}.json").read_text(encoding="utf-8"))
        base_labels: dict[str, str] = dict(niche_data.get("section_labels", {}))
        variants: dict[str, list[str]] = niche_data.get("section_label_variants", {})
        variant_idx = int(hashlib.md5(site_id.encode()).hexdigest(), 16) % 3 if site_id else 0
        for key, v_list in variants.items():
            if v_list:
                base_labels[key] = v_list[variant_idx % len(v_list)]
        niche_labels = base_labels
    except Exception:
        pass
merged_labels = {**niche_labels, **c.get("section_labels_override", {})}

fields = {
  "SITE_URL":                    d.get("site_url", ""),
  "PUBLIC_SITE_NAME":            b.get("name", ""),
  "PUBLIC_SITE_NAME_FULL":       b.get("name_full", ""),
  "PUBLIC_METRIKA_ID":           a.get("metrika_id", ""),
  "PUBLIC_COMPANY_PHONE":        ct.get("phone", ""),
  "PUBLIC_COMPANY_PHONE_HREF":   ct.get("phone_href", ""),
  "PUBLIC_COMPANY_PHONE_LABEL":  ct.get("phone_label", ""),
  "PUBLIC_COMPANY_EMAIL":        ct.get("email", ""),
  "PUBLIC_COMPANY_ADDRESS":      ct.get("address", ""),
  "PUBLIC_COMPANY_WORKTIME":     ct.get("worktime", ""),
  "PUBLIC_CONTACT_FORM_ACTION":  f.get("action", "/mail.php"),
  "PUBLIC_CONTACT_FORM_TO":      f.get("to", ""),
  "PUBLIC_CONTACT_FORM_SUBJECT": f.get("subject", ""),
  "YANDEX_METRICA_ID":           "",
  "GTAG_ID":                     a.get("gtag_id", ""),
  "BEGET_HOST":                  d.get("beget_host", ""),
  "BEGET_FTP_USER":              d.get("beget_ftp_user", ""),
  "BEGET_FTP_PATH":              d.get("beget_ftp_path", "/"),
  "CONTENT_OUTPUT_DIR":          c.get("content_dir", ""),
  "ENABLE_EDITORIAL_POSTS":      str(c.get("enable_editorial_posts", True)).lower(),
  "PUBLIC_THEME":                c.get("theme", "alpha"),
  "PUBLIC_CONTACT_PATH":         c.get("contact_path", "/kontakty/"),
  "PUBLIC_LEGACY_SOURCE_DOMAIN": c.get("legacy_source_domain", ""),
  "PUBLIC_LEGACY_BRAND_ALIASES": c.get("legacy_brand_aliases", ""),
  "PUBLIC_SITE_STATS":           "|".join(c.get("site_stats", [])),
  "PUBLIC_NICHE_CTA_QUESTION":   c.get("niche_cta", {}).get("article_question", "Есть вопросы?"),
  "PUBLIC_NICHE_CTA_BTN":        c.get("niche_cta", {}).get("article_btn", "Задать вопрос"),
  "PUBLIC_NICHE_SIDEBAR_TITLE":  c.get("niche_cta", {}).get("sidebar_title", "Нужна помощь?"),
  "PUBLIC_NICHE_SIDEBAR_DESC":   c.get("niche_cta", {}).get("sidebar_desc", "Свяжитесь с нами."),
  "PUBLIC_NICHE_SIDEBAR_BTN":    c.get("niche_cta", {}).get("sidebar_btn", "Получить консультацию"),
  "PUBLIC_SECTION_LABELS":       json.dumps(merged_labels, ensure_ascii=False),
  "PUBLIC_SHOW_DATE":            str(c.get("article_meta", {}).get("show_date", True)).lower(),
  "PUBLIC_SHOW_READING_TIME":    str(c.get("article_meta", {}).get("show_reading_time", False)).lower(),
  "PUBLIC_SHOW_AUTHOR":          str(c.get("article_meta", {}).get("show_author", False)).lower(),
  "PUBLIC_META_TEMPLATES":       "|".join(c.get("meta_templates", [])),
}
for k, v in fields.items():
    print(f"{k}={v}")
PYEOF

PARSED=$(python3 - "$CONFIG" "$SITE_ID" <<< "$PARSE_SCRIPT")

cat > "$ENV_FILE" << EOF
# Generated by gen-env.sh from $CONFIG
# DO NOT EDIT manually — edit $CONFIG instead.
# Secrets (FTP password, API keys) are preserved from previous site/.env.

${PARSED}

FIRECRAWL_API_KEY=${FIRECRAWL_API_KEY}
EXA_API_KEY=${EXA_API_KEY}

BEGET_FTP_PASS=${BEGET_FTP_PASS}
EOF

echo "✓ site/.env written for site_id=${SITE_ID}"
echo "  Review site/.env and fill in any blank secrets before deploying."

# affiliate.ts statically imports site/src/data/{affiliateLinks,promoSlots}.json —
# per-site data lives in sites/<SITE_ID>/ and must be copied in before build.
for f in affiliateLinks.json promoSlots.json; do
  SRC="sites/${SITE_ID}/${f}"
  DEST="site/src/data/${f}"
  if [[ -f "$SRC" ]]; then
    cp "$SRC" "$DEST"
    echo "✓ ${DEST} ← ${SRC}"
  else
    echo "⚠ ${SRC} not found — leaving ${DEST} as-is" >&2
  fi
done

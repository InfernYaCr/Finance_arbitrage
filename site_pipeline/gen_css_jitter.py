#!/usr/bin/env python3
"""
gen_css_jitter.py — Generate per-site CSS token jitter for footprint diversity.

Produces site/src/styles/themes/jitter.css with small deterministic variations
in border-radius (±2px) and spacing scale (±5%) based on site_id seed.

Usage:
  python site_pipeline/gen_css_jitter.py --site-id vsezaimyonline
  python site_pipeline/gen_css_jitter.py --site-id vsezaimyonline --out site/src/styles/themes/jitter.css
"""

from __future__ import annotations

import argparse
import hashlib
import random
from pathlib import Path

PROJECT_ROOT = Path(__file__).parent.parent


def _seed_rng(site_id: str) -> random.Random:
    digest = int(hashlib.md5(site_id.encode()).hexdigest(), 16)
    return random.Random(digest)


def generate_jitter_css(site_id: str) -> str:
    rng = _seed_rng(site_id)

    # Border-radius jitter: ±2px from defaults
    def jitter_radius(base_rem: float) -> str:
        px_delta = rng.randint(-2, 2)
        return f"calc({base_rem}rem + {px_delta}px)"

    # Spacing jitter: ±5% scale factor
    scale = 1.0 + rng.uniform(-0.05, 0.05)

    def jitter_space(base_rem: float) -> str:
        adjusted = round(base_rem * scale, 4)
        return f"{adjusted}rem"

    lines = [
        f"/* Auto-generated by gen_css_jitter.py — site: {site_id} — do not edit */",
        f":root {{",
        f"  --radius-sm: {jitter_radius(0.25)};",
        f"  --radius-md: {jitter_radius(0.5)};",
        f"  --radius-lg: {jitter_radius(0.75)};",
        f"  --radius-xl: {jitter_radius(1.0)};",
        f"",
        f"  --space-3: {jitter_space(0.75)};",
        f"  --space-4: {jitter_space(1.0)};",
        f"  --space-5: {jitter_space(1.25)};",
        f"  --space-6: {jitter_space(1.5)};",
        f"  --space-8: {jitter_space(2.0)};",
        f"  --space-10: {jitter_space(2.5)};",
        f"  --space-12: {jitter_space(3.0)};",
        f"}}",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate CSS token jitter for a site.")
    parser.add_argument("--site-id", required=True, help="Site ID (e.g. vsezaimyonline)")
    parser.add_argument(
        "--out", type=Path, default=None,
        help="Output CSS path (default: site/src/styles/themes/jitter.css)",
    )
    args = parser.parse_args()

    css = generate_jitter_css(args.site_id)
    out_path = args.out or (PROJECT_ROOT / "site" / "src" / "styles" / "themes" / "jitter.css")
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(css, encoding="utf-8")
    print(f"✓ CSS jitter → {out_path}  (site_id={args.site_id!r})")
    print(css)


if __name__ == "__main__":
    main()
